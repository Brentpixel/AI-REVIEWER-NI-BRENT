(function () {
  const dropZone    = document.getElementById('rqDropZone');
  const fileInput   = document.getElementById('rqFileInput');
  const fileInfo    = document.getElementById('rqFileInfo');
  const fileName    = document.getElementById('rqFileName');
  const fileMeta    = document.getElementById('rqFileMeta');
  const fileError   = document.getElementById('rqFileError');
  const form        = document.getElementById('rqUploadForm');
  const loadingOverlay = document.getElementById('rqLoadingOverlay');
  const MAX_SIZE    = 10 * 1024 * 1024;
  const ALLOWED_EXT = ['pdf','docx','txt'];

  function formatSize(bytes) {
    if (bytes < 1024) return bytes + ' B';
    if (bytes < 1048576) return (bytes/1024).toFixed(1) + ' KB';
    return (bytes/1048576).toFixed(2) + ' MB';
  }

  function showFileInfo(file) {
    const ext = file.name.split('.').pop().toLowerCase();
    fileError.classList.add('d-none');
    fileInfo.classList.remove('d-none');
    fileName.textContent = file.name;
    fileMeta.textContent = ext.toUpperCase() + '  \u00B7  ' + formatSize(file.size);
  }

  function validateFile(file) {
    const ext = file.name.split('.').pop().toLowerCase();
    if (!ALLOWED_EXT.includes(ext)) {
      fileError.textContent = 'Unsupported file type. Please upload PDF, DOCX, or TXT.';
      fileError.classList.remove('d-none');
      fileInfo.classList.add('d-none');
      return false;
    }
    if (file.size > MAX_SIZE) {
      fileError.textContent = 'File exceeds the 10 MB limit. Please choose a smaller file.';
      fileError.classList.remove('d-none');
      fileInfo.classList.add('d-none');
      return false;
    }
    return true;
  }

  fileInput.addEventListener('change', function () {
    if (this.files.length > 0) {
      if (validateFile(this.files[0])) showFileInfo(this.files[0]);
    }
  });

  dropZone.addEventListener('dragover', e => { e.preventDefault(); dropZone.classList.add('drag-over'); });
  dropZone.addEventListener('dragleave', () => dropZone.classList.remove('drag-over'));
  dropZone.addEventListener('drop', e => {
    e.preventDefault(); dropZone.classList.remove('drag-over');
    const file = e.dataTransfer.files[0];
    if (file) {
      const dt = new DataTransfer();
      dt.items.add(file);
      fileInput.files = dt.files;
      if (validateFile(file)) showFileInfo(file);
    }
  });

  form.addEventListener('submit', function (e) {
    if (!fileInput.files.length) {
      e.preventDefault();
      fileError.textContent = 'Please select a file before submitting.';
      fileError.classList.remove('d-none');
      return;
    }
    if (!validateFile(fileInput.files[0])) { e.preventDefault(); return; }
    loadingOverlay.classList.add('active');
  });
})();
</script>

